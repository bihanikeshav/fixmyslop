#!/usr/bin/env python3
"""Export the deterministic local-suite ledger consumed by the landing page."""
from __future__ import annotations

import json
from pathlib import Path

from local_benchmark_suite import run

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "apps" / "web" / "demo" / "textslop-summary.js"


def build_summary(report: dict[str, object]) -> dict[str, object]:
    owned = report["owned_rewrite_benchmark"]
    systems = owned["systems"]
    return {
        "suite": report["suite"],
        "version": report["version"],
        "ownedFixtures": owned["items"],
        "interventionCases": report["intervention"]["items"],
        "claimMutations": report["claimflip"]["items"],
        "identityBaseline": "identity/no-op" in systems,
        "comparisonPolicy": report["comparison_policy"],
    }


def render_js(summary: dict[str, object]) -> str:
    payload = json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True)
    return (
        "// Generated by textslopbench/export_web_summary.py. Do not hand-edit.\n"
        f"window.TEXTSLOP_SUMMARY = Object.freeze({payload});\n"
    )


def main() -> int:
    OUTPUT.write_text(render_js(build_summary(run())), encoding="utf-8")
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
